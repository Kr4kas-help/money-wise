import { quotes, rules, type Rule } from "./wisdom";
import { categoryLabels, type Summary } from "./spending";
import { rub, type Problem } from "./types";

export type Advice = {
  kind: "control" | "first" | "track";
  headline: string;
  quotes: string[];
  hero: string;
  storyTitle: string;
  story: string[]; // краткая история, абзацы
  rule: Rule;
  step: string; // конкретное действие для этого человека
};

// Истории пересказаны своими словами по мотивам книги Дж. Клейсона
// «Самый богатый человек в Вавилоне». Это не дословные цитаты перевода.
export function pickAdvice(s: Summary, problems: Problem[]): Advice {
  const pct = Math.round(s.wasteShare * 100);

  // 1. Много лишнего: учимся отличать нужное от желаемого.
  if (s.wasteShare >= 0.25) {
    const top = s.topCategory ? categoryLabels[s.topCategory] : "разное";
    return {
      kind: "control",
      headline: `Лишним вы назвали ${rub(s.waste)} — это ${pct}% всех трат.`,
      quotes: [quotes[2].text, quotes[6].text],
      hero: "Аркад",
      storyTitle: "Аркад и роспись расходов",
      story: [
        "Аркад начинал простым писцом, а стал самым богатым человеком Вавилона. Ученикам он объяснял: у кошелька нет дна, пока человек не отличает нужное от желаемого.",
        "Он советовал сесть и записать всё, на что уходят деньги, а потом вычеркнуть то, без чего можно прожить. То, что осталось, и есть настоящая жизнь по средствам.",
        "Заметил он и другое: когда перестаёшь тратить на лишнее, беднее себя не чувствуешь. Просто деньги наконец остаются у тебя.",
      ],
      rule: rules[1],
      step: `Больше всего лишнего ушло на «${top}»: ${rub(s.topAmount)}. Сократите такие траты вдвое: это ${rub(s.waste / 2)} за тот же срок, который вы разбирали. Переводите эту сумму на отдельный счёт в день выплаты, до всех покупок.`,
    };
  }

  // 2. Лишнего немного, но человек не понимает, куда уходят деньги.
  if (problems.includes("no_plan") || problems.includes("no_money")) {
    return {
      kind: "track",
      headline: `Почти всё необходимое: лишнего всего ${pct}%. Значит, дело не в мелких покупках.`,
      quotes: [quotes[5].text, quotes[1].text],
      hero: "Банзир",
      storyTitle: "Колесничий Банзир и музыкант Кобби",
      story: [
        "Колесничий Банзир и музыкант Кобби честно работали, но кошельки у них были пусты. Они не понимали, почему одни богатеют, а они нет.",
        "Они пошли к Аркаду и услышали: дело не в том, сколько ты получаешь, а в том, что остаётся у тебя. Сначала надо увидеть, куда уходит золото, и взять себе свою долю.",
        "Сегодня вы сделали тот же первый шаг: выписали траты и посмотрели на них прямо.",
      ],
      rule: rules[0],
      step: "Неделю записывайте каждую трату сразу после покупки, хотя бы в заметках телефона. В день выплаты отложите десятую долю дохода раньше любых расходов.",
    };
  }

  // 3. Траты в основном нужные: проблема в порядке, а не в привычках.
  return {
    kind: "first",
    headline: `Необходимого у вас ${100 - pct}% трат. Дело в порядке: деньги уходят раньше, чем вы их откладываете.`,
    quotes: [quotes[0].text, quotes[9].text],
    hero: "Алгамиш",
    storyTitle: "Алгамиш и десятая часть",
    story: [
      "Молодой Аркад работал писцом у ростовщика Алгамиша и зарабатывал не хуже других, но ничего не копил. Он спросил Алгамиша, как стать богатым.",
      "Алгамиш ответил: часть всего, что ты зарабатываешь, принадлежит тебе. Откладывай её первой, не меньше десятой доли, а жить продолжай на остальное.",
      "Аркад так и сделал и вскоре заметил, что девяти десятых заработка хватает на жизнь так же, как хватало всего. А отложенное начало работать на него.",
    ],
    rule: rules[0],
    step: "В день выплаты сразу переведите десятую долю дохода на отдельный счёт, до любых покупок, и живите на остальное. Лучше настроить автоматический перевод.",
  };
}
