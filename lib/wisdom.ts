// Номер мысли дня: от него шапка начинает вращение цитат.
export function quoteIndex(date = new Date()): number {
  const start = new Date(date.getFullYear(), 0, 0).getTime();
  const day = Math.floor((date.getTime() - start) / 86400000);
  return day % quotes.length;
}

export function quoteOfDay(date = new Date()): Quote {
  return quotes[quoteIndex(date)];
}
